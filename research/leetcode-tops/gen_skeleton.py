"""Write skeleton/leetcode-tops.yaml from research/leetcode-tops/selection.json and fetch missing statements.

    uv run python research/leetcode-tops/gen_skeleton.py

17 topic branches with the deck names the old deck used (LeetCode Tops::01 .. ::17), one leaf per problem, problems in
order of company-tag frequency (high first; easier first among close ranks). Leaves in the global top 150 are `core`,
so a study session deals them before the rest of every branch. Statements go to sources/local/leetcode-tops/<slug>.txt.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from leetcode_daily import question, to_text  # noqa: E402

BRANCHES = [("arrays-hashing", "数组与哈希（arrays & hashing）"), ("two-pointers", "双指针（two pointers）"),
            ("sliding-window", "滑动窗口（sliding window）"), ("stack", "栈与单调栈（stack）"),
            ("binary-search", "二分查找（binary search）"), ("linked-list", "链表（linked list）"),
            ("trees", "二叉树与二叉搜索树（trees）"), ("tries", "字典树（trie）"),
            ("heap-priority-queue", "堆与优先队列（heap / priority queue）"), ("backtracking", "回溯（backtracking）"),
            ("graphs", "图与搜索（graphs）"), ("dp-1d", "一维动态规划（1-D DP）"), ("dp-2d", "二维动态规划（2-D DP）"),
            ("greedy", "贪心（greedy）"), ("intervals", "区间（intervals）"), ("math-geometry", "数学与几何（math & geometry）"),
            ("bit-manipulation", "位运算（bit manipulation）")]
STATEMENTS = ROOT / "sources/local/leetcode-tops"
META = ROOT / "research/leetcode-tops/meta.json"


def main() -> None:
    sel = json.loads((ROOT / "research/leetcode-tops/selection.json").read_text(encoding="utf-8"))
    meta = json.loads(META.read_text(encoding="utf-8")) if META.exists() else {}
    STATEMENTS.mkdir(parents=True, exist_ok=True)
    for p in sel:
        s = p["slug"]
        if s in meta and (STATEMENTS / f"{s}.txt").exists():
            continue
        q = question(s)
        (STATEMENTS / f"{s}.txt").write_text(to_text(q.get("translatedContent") or q.get("content") or ""), encoding="utf-8")
        meta[s] = {"id": int(q.get("questionFrontendId") or 0), "title": q.get("title") or p["title"],
                   "title_zh": q.get("translatedTitle") or q.get("title") or p["title"],
                   "difficulty": q.get("difficulty") or p["difficulty"]}
        time.sleep(0.3)
    META.write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")
    rank = {"Easy": 0, "Medium": 1, "Hard": 2}
    nodes = []
    for i, (bid, title) in enumerate(BRANCHES, 1):
        ps = [p for p in sel if p["branch"] == bid]
        ps.sort(key=lambda p: ((p["rank"] or 9999) // 25, rank.get(meta[p["slug"]]["difficulty"], 1), p["rank"] or 9999))
        leaves = []
        for p in ps:
            m = meta[p["slug"]]
            name = f"LC {m['id']} {m['title_zh']}" + (f"（{m['title']}）" if m["title_zh"] != m["title"] else "")
            where = f"全公司热度第 {p['rank']} 名" if p["rank"] else "题单题"
            leaf = {"id": f"{bid}.{p['slug']}", "title": name,
                    "summary": f"{m['difficulty']}；{where}" + (f"；{'、'.join(p['lists'])}" if p["lists"] else "") + "。"}
            if p["rank"] and p["rank"] <= 150:
                leaf["core"] = True
            leaves.append(leaf)
        nodes.append({"id": bid, "order": i, "title": title,
                      "summary": f"{title}：按全公司出题频率从高到低，频率相近时先易后难；每题一张整题卡。", "children": leaves})
    sk = {"domain": "leetcode-tops", "title": "LeetCode Tops", "deck": "LeetCode Tops", "lang": "zh",
          "vault": "interviews/core/leetcode/tops",
          "examples_from": "interviews/core/leetcode/tops/cards,interviews/core/leetcode/tiktok/cards",
          # no per-day limits: the root preset is shared with decks 18-20 and stays as Chi set it
          "study": {"order": "core-first", "mix": "new-first"}, "nodes": nodes}
    (ROOT / "skeleton/leetcode-tops.yaml").write_text(
        "# LeetCode Tops topic decks 01-17: ~370 problems chosen by company-tag frequency + classic lists (80/20).\n"
        "# Generated by research/leetcode-tops/gen_skeleton.py from selection.json; re-run to regenerate.\n"
        + yaml.safe_dump(sk, allow_unicode=True, sort_keys=False, width=200), encoding="utf-8")
    print(sum(len(n["children"]) for n in nodes), "leaves;", sum(1 for n in nodes for c in n["children"] if c.get("core")), "core")


if __name__ == "__main__":
    main()
