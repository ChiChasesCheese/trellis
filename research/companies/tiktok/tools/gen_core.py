"""Build the `tiktok-core` deck: tier-A problems that are also on Amazon or the classic lists, copied for one pass.

    uv run python research/companies/tiktok/tools/gen_core.py

Chi (2026-10-30): problems that are frequent at TikTok *and* appear in his Amazon decks or in Blind 75 / NeetCode 150 /
LeetCode Hot 100 / Top Interview 150 carry the most general patterns, so he wants them as their own deck to go through
first. Each card is a copy of the problem's whole-answer card (new id `tlc-core-<slug>`, so it has its own schedule),
with the lists it appears on added to the header. Sub-decks follow the tier-A priorities P1..P5. Re-run after the
TikTok deck changes; it rewrites skeleton/tiktok-core.yaml and the cards.
"""
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[4]
TT = ROOT / "research/companies/tiktok"
index = json.loads((TT / "index.json").read_text(encoding="utf-8"))
lists = json.loads((TT / "catalog/other_lists.json").read_text(encoding="utf-8"))
NAMES = ["Amazon", "LeetCode Hot 100", "Blind 75", "NeetCode 150", "Top Interview 150"]
SRC = ROOT / "vault/interviews/core/leetcode/tiktok/cards"
OUT = ROOT / "vault/interviews/core/leetcode/tiktok-core/cards"
BAND = {"p1": "P1 最高频", "p2": "P2 高频", "p3": "P3 常见", "p4": "P4 较常见", "p5": "P5 A 档其余"}

core = []
for slug, p in index.items():
    on = [name for name in NAMES if p.get("id") in set(lists[name])]
    if p["tier"] == "A" and on:
        core.append((p, on))
core.sort(key=lambda x: (x[0]["band"], -x[0].get("score", 0)))

written = set()
for p, on in core:
    src = next(SRC.glob(f"*/tlc-{p['slug']}-0-whole.md"), None)
    if src is None:
        continue
    text = src.read_text(encoding="utf-8")
    text = re.sub(r"^id: .*$", f"id: tlc-core-{p['slug']}", text, count=1, flags=re.M)
    text = re.sub(r"^node: .*$", f"node: {p['band']}.{p['slug']}", text, count=1, flags=re.M)
    text = re.sub(r"^(\*\*[^*\n]+\*\*｜[^\n]*)$", lambda m: m.group(1) + " · 也在：" + "、".join(on), text, count=1, flags=re.M)
    dest = OUT / p["band"] / f"tlc-core-{p['slug']}.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8")
    written.add(dest)
for f in OUT.glob("*/*.md"):  # a problem that left the core list
    if f not in written:
        f.unlink()

nodes = []
for i, band in enumerate(("p1", "p2", "p3", "p4", "p5"), 1):
    leaves = [(p, on) for p, on in core if p["band"] == band]
    if leaves:
        nodes.append({"id": band, "order": i, "core": True, "title": f"{BAND[band]}（{len(leaves)} 题）",
                      "summary": "TikTok 高频且也在 Amazon 或经典题单里的题，同一优先级里高频在前。",
                      "children": [{"id": f"{band}.{p['slug']}",
                                    "title": f"LC {p['id']} {p.get('title_zh') or p['title']}",
                                    "summary": "也在：" + "、".join(on) + "。"} for p, on in leaves]})
sk = {"domain": "tiktok-core", "title": "通用核心：TikTok 高频 × Amazon × 经典题单",
      "deck": "LeetCode Tops::27 通用核心：TikTok 高频 × Amazon × 经典题单",
      "lang": "zh", "vault": "interviews/core/leetcode/tiktok-core",
      "study": {"order": "core-first", "mix": "new-first", "new_per_day": 60, "reviews_per_day": 300},
      "nodes": nodes}
hdr = ("# Tier-A TikTok problems that are also on Amazon or classic lists, one copy of each whole-answer card.\n"
       "# Generated by research/companies/tiktok/tools/gen_core.py; re-run to regenerate.\n")
(ROOT / "skeleton/tiktok-core.yaml").write_text(hdr + yaml.safe_dump(sk, allow_unicode=True, sort_keys=False, width=200),
                                                encoding="utf-8")
print(len(written), "cards;", {n["id"]: len(n["children"]) for n in nodes})
