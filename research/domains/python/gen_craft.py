"""Add or refresh the `craft` branch of skeleton/python.yaml from research/domains/python/craft_map.json.

    uv run python research/domains/python/gen_craft.py        # also writes craft_group_X*.txt

Everything after the marker line in the skeleton is generated.
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
SK = ROOT / "skeleton/python.yaml"
MAP = ROOT / "research/domains/python/craft_map.json"
MARK = "# craft: generated by research/domains/python/gen_craft.py\n"
TITLES = {"patterns": ("跨题模式（Patterns）", "反复出现在不同题目里的机制：同一个思路在每道题里怎么用、哪里不同、新题看到什么信号要想到它。"),
          "idioms": ("高级写法（Idioms）", "真实代码里的 Python 用法：底层做了什么、朴素写法的代价、什么时候不该用。"),
          "architecture": ("架构理解（Architecture）", "类之上的判断：依赖方向、事务边界、哪里值得抽象，以及同一设计从单进程到分布式怎么变。")}
ORDER = ("patterns", "idioms", "architecture")
GROUP_SIZE = 18


def main() -> None:
    data = {b["id"]: b["leaves"] for b in json.loads(MAP.read_text(encoding="utf-8"))["branches"]}
    known = set()

    def walk(n: dict) -> None:
        known.add(n["id"])
        for c in n.get("children", []):
            walk(c)

    text = SK.read_text(encoding="utf-8").split(MARK)[0]
    for n in yaml.safe_load(text)["nodes"]:
        walk(n)
    kids = []
    for bid in ORDER:
        title, summary = TITLES[bid]
        leaves = []
        for x in data[bid]:
            leaf = {"id": f"craft.{bid}.{x['id']}", "title": x["title"], "summary": x["summary"]}
            req = [r for r in x.get("language_leaves", []) if r in known]
            if req:
                leaf["requires"] = req
            leaves.append(leaf)
        kids.append({"id": f"craft.{bid}", "title": title, "summary": summary, "children": leaves})
    orders = [n.get("order", 0) for n in yaml.safe_load(text)["nodes"]]
    node = {"id": "craft", "order": max(orders) + 1, "title": "编码功力（Coding Craft）",
            "summary": "把语言知识用到真实代码里：写法、跨题共性和架构判断，从 LLD 题的参考解中提炼。", "children": kids}
    body = yaml.safe_dump([node], allow_unicode=True, sort_keys=False, width=200)
    SK.write_text(text + MARK + body, encoding="utf-8")
    n = 0
    for bid in ORDER:
        ids = [f"{bid} {x['id']}" for x in data[bid]]
        for j in range(0, len(ids), GROUP_SIZE):
            n += 1
            (ROOT / f"research/domains/python/craft_group_X{n}.txt").write_text("\n".join(ids[j:j + GROUP_SIZE]) + "\n", encoding="utf-8")
    print(sum(len(v) for v in data.values()), "leaves;", n, "groups")


if __name__ == "__main__":
    main()
